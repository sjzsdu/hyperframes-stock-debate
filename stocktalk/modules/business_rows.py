"""主营构成行分类的口径常量（只有常量，没有逻辑）。

F10 的「主营构成·明细」把三类完全不同的东西挤在同一张表里，只能靠行名后缀区分：

* 产品行  —— 真正的业务块（``茅台酒(产品)``、``其他系列酒(产品)``），图上画成卡组/分支；
* 渠道行  —— ``直销(销售模式)`` / ``批发代理(销售模式)``，是"货怎么到客户手上"那一层；
* 地区行  —— ``国内(地区)`` / ``国外(地区)``，同样属于渠道那一层；
* 行业行  —— ``汽车零部件(行业)``，是它的行业归属，**不是它卖的东西**。

这个模块单独存在的理由：``episode_planner`` 与 ``hyperframes_builder`` 都要用这套口径
（素材抽取 vs 兜底渲染器），但两者之间已有 ``story_spotter → hyperframes_builder`` 的
依赖，直接互相 import 会成环。口径只能有一处，所以放在这里。
"""

from __future__ import annotations

# 渠道/地区行：单独成一类素材（mat.channel.0），不进产品线。
CHANNEL_ROW_SUFFIXES: tuple[str, ...] = ("(销售模式)", "(地区)")

# 所有**不属于产品线**的行后缀。``(行业)`` 只在这里出现——它既不是产品也不是渠道，
# 曾经被当成产品线画上卡组，第一张卡就是行业名。
NON_PRODUCT_ROW_SUFFIXES: tuple[str, ...] = CHANNEL_ROW_SUFFIXES + ("(行业)",)
